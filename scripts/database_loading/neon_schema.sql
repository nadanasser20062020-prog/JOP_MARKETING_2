BEGIN;

CREATE TABLE IF NOT EXISTS public.data_sources (
    source_dataset TEXT PRIMARY KEY,
    display_name TEXT NOT NULL,
    notes TEXT
);

CREATE TABLE IF NOT EXISTS public.source_files (
    source_dataset TEXT NOT NULL,
    source_file TEXT NOT NULL,
    snapshot_group TEXT NOT NULL CHECK (
        snapshot_group IN ('historical_sample', 'latest_export', 'other_snapshot')
    ),
    snapshot_type TEXT NOT NULL CHECK (
        snapshot_type IN (
            'historical_2023_sample',
            'latest_export_listing_status_unverified',
            'merged_source_snapshot_date_semantics_unverified',
            'regional_snapshot_date_coverage_partial',
            'regional_snapshot_date_unavailable'
        )
    ),
    notes TEXT,
    PRIMARY KEY (source_dataset, source_file),
    UNIQUE (source_dataset, source_file, snapshot_type),
    FOREIGN KEY (source_dataset)
        REFERENCES public.data_sources (source_dataset)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.import_runs (
    import_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_status TEXT NOT NULL DEFAULT 'running' CHECK (
        run_status IN ('running', 'succeeded', 'failed')
    ),
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    pipeline_version TEXT,
    quality_report JSONB,
    notes TEXT,
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE TABLE IF NOT EXISTS public.import_run_files (
    import_run_id BIGINT NOT NULL,
    source_dataset TEXT NOT NULL,
    source_file TEXT NOT NULL,
    rows_read BIGINT NOT NULL DEFAULT 0 CHECK (rows_read >= 0),
    rows_loaded BIGINT NOT NULL DEFAULT 0 CHECK (rows_loaded >= 0),
    rows_rejected BIGINT NOT NULL DEFAULT 0 CHECK (rows_rejected >= 0),
    import_status TEXT NOT NULL DEFAULT 'pending' CHECK (
        import_status IN ('pending', 'succeeded', 'partially_succeeded', 'failed')
    ),
    notes TEXT,
    PRIMARY KEY (import_run_id, source_dataset, source_file),
    FOREIGN KEY (import_run_id)
        REFERENCES public.import_runs (import_run_id)
        ON DELETE CASCADE,
    FOREIGN KEY (source_dataset, source_file)
        REFERENCES public.source_files (source_dataset, source_file)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.skills (
    skill_id TEXT PRIMARY KEY,
    canonical_name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'uncategorized',
    match_policy TEXT NOT NULL CHECK (
        match_policy IN ('approved_aliases', 'exact_only', 'exclude_pending_review')
    ),
    review_status TEXT NOT NULL CHECK (
        review_status IN ('curated', 'curated_exact_only', 'needs_review', 'needs_owner_review')
    ),
    observed_alias_count INTEGER NOT NULL DEFAULT 0 CHECK (observed_alias_count >= 0),
    observed_source_count INTEGER NOT NULL DEFAULT 0 CHECK (observed_source_count >= 0),
    observed_job_skill_occurrences BIGINT NOT NULL DEFAULT 0
        CHECK (observed_job_skill_occurrences >= 0),
    notes TEXT
);

CREATE TABLE IF NOT EXISTS public.skill_aliases (
    alias_normalized TEXT PRIMARY KEY,
    alias_label TEXT NOT NULL,
    skill_id TEXT NOT NULL,
    alias_type TEXT NOT NULL,
    match_policy TEXT NOT NULL CHECK (
        match_policy IN ('approved_aliases', 'exact_only', 'exclude_pending_review')
    ),
    review_status TEXT NOT NULL CHECK (
        review_status IN ('curated', 'curated_exact_only', 'needs_review', 'needs_owner_review')
    ),
    observed_source_count INTEGER NOT NULL DEFAULT 0 CHECK (observed_source_count >= 0),
    observed_job_skill_occurrences BIGINT NOT NULL DEFAULT 0
        CHECK (observed_job_skill_occurrences >= 0),
    notes TEXT,
    FOREIGN KEY (skill_id)
        REFERENCES public.skills (skill_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.jobs (
    record_id TEXT PRIMARY KEY,
    source_dataset TEXT NOT NULL,
    source_file TEXT NOT NULL,
    source_row_number INTEGER NOT NULL CHECK (source_row_number > 0),
    source_record_id TEXT,
    record_origin TEXT,
    source_platform TEXT,
    title TEXT,
    title_short TEXT,
    company TEXT,
    country TEXT,
    city TEXT,
    region TEXT,
    location_raw TEXT,
    work_mode_raw TEXT,
    remote_flag TEXT,
    employment_type_raw TEXT,
    experience_raw TEXT,
    category_raw TEXT,
    description TEXT,
    posted_at TEXT,
    source_updated_at TEXT,
    source_date_field TEXT NOT NULL CHECK (
        source_date_field IN (
            'posted_at_or_job_posted_date',
            'updated_semantics_unverified',
            'not_available'
        )
    ),
    salary_raw TEXT,
    salary_rate TEXT,
    salary_year_avg TEXT,
    salary_hour_avg TEXT,
    salary_currency TEXT,
    salary_basis TEXT,
    salary_source TEXT,
    salary_provenance_status TEXT NOT NULL CHECK (
        salary_provenance_status IN (
            'estimate_or_research_indicated',
            'source_or_origin_unverified',
            'not_available'
        )
    ),
    skills TEXT,
    skills_original TEXT,
    skills_source TEXT,
    skills_enrichment_status TEXT NOT NULL CHECK (
        skills_enrichment_status IN (
            'not_compared',
            'matches_source_version',
            'changed_source_version_unverified',
            'base_row_not_found_or_id_missing'
        )
    ),
    source_url TEXT,
    listing_status TEXT NOT NULL DEFAULT 'unknown_not_verified',
    snapshot_type TEXT NOT NULL,
    exact_duplicate_within_source TEXT NOT NULL CHECK (
        exact_duplicate_within_source IN ('yes', 'no')
    ),
    data_quality_flags TEXT NOT NULL DEFAULT '',
    UNIQUE (source_dataset, source_file, source_row_number),
    UNIQUE (record_id, source_dataset, source_file),
    FOREIGN KEY (source_dataset, source_file, snapshot_type)
        REFERENCES public.source_files (source_dataset, source_file, snapshot_type)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.job_skills (
    record_id TEXT NOT NULL,
    source_dataset TEXT NOT NULL,
    source_file TEXT NOT NULL,
    skill_raw TEXT NOT NULL,
    skill_normalized TEXT NOT NULL,
    skill_id TEXT NOT NULL,
    skill_category TEXT NOT NULL,
    skill_match_policy TEXT NOT NULL CHECK (
        skill_match_policy IN ('approved_aliases', 'exact_only', 'exclude_pending_review')
    ),
    skill_review_status TEXT NOT NULL CHECK (
        skill_review_status IN ('curated', 'curated_exact_only', 'needs_review', 'needs_owner_review')
    ),
    skill_provenance TEXT NOT NULL DEFAULT '',
    skill_status TEXT NOT NULL CHECK (
        skill_status IN (
            'present_in_base_export',
            'added_in_enriched_export_provenance_unverified',
            'row_level_mixed_provenance_no_per_skill_lineage',
            'source_field_provenance_not_supplied'
        )
    ),
    PRIMARY KEY (record_id, skill_id),
    FOREIGN KEY (record_id, source_dataset, source_file)
        REFERENCES public.jobs (record_id, source_dataset, source_file)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    FOREIGN KEY (skill_id)
        REFERENCES public.skills (skill_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.skill_observations (
    source_dataset TEXT NOT NULL,
    skill_raw TEXT NOT NULL,
    skill_normalized TEXT NOT NULL,
    occurrence_count BIGINT NOT NULL CHECK (occurrence_count >= 0),
    PRIMARY KEY (source_dataset, skill_normalized),
    FOREIGN KEY (source_dataset)
        REFERENCES public.data_sources (source_dataset)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    FOREIGN KEY (skill_normalized)
        REFERENCES public.skill_aliases (alias_normalized)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.learning_resources (
    resource_id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    provider TEXT NOT NULL,
    resource_type TEXT NOT NULL,
    skill_ids TEXT NOT NULL,
    languages TEXT NOT NULL,
    level TEXT NOT NULL,
    access_status TEXT NOT NULL,
    cost_status TEXT NOT NULL CHECK (
        cost_status IN ('free_verified', 'some_free_options', 'conditional_or_mixed', 'cost_unverified')
    ),
    account_requirement TEXT NOT NULL,
    credential TEXT NOT NULL,
    resource_url TEXT NOT NULL CHECK (resource_url LIKE 'https://%'),
    verification_status TEXT NOT NULL,
    verified_on DATE NOT NULL,
    notes TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS public.learning_resource_skills (
    resource_id TEXT NOT NULL,
    skill_id TEXT NOT NULL,
    PRIMARY KEY (resource_id, skill_id),
    FOREIGN KEY (resource_id)
        REFERENCES public.learning_resources (resource_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    FOREIGN KEY (skill_id)
        REFERENCES public.skills (skill_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.learning_resource_languages (
    resource_id TEXT NOT NULL,
    language TEXT NOT NULL,
    PRIMARY KEY (resource_id, language),
    FOREIGN KEY (resource_id)
        REFERENCES public.learning_resources (resource_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS jobs_source_dataset_idx
    ON public.jobs (source_dataset);
CREATE INDEX IF NOT EXISTS jobs_source_file_idx
    ON public.jobs (source_dataset, source_file);
CREATE INDEX IF NOT EXISTS jobs_country_idx
    ON public.jobs (country);
CREATE INDEX IF NOT EXISTS jobs_category_raw_idx
    ON public.jobs (category_raw);
CREATE INDEX IF NOT EXISTS jobs_snapshot_type_idx
    ON public.jobs (snapshot_type);
CREATE INDEX IF NOT EXISTS jobs_listing_status_idx
    ON public.jobs (listing_status);
CREATE INDEX IF NOT EXISTS jobs_source_record_id_idx
    ON public.jobs (source_record_id);
CREATE INDEX IF NOT EXISTS job_skills_skill_id_idx
    ON public.job_skills (skill_id);
CREATE INDEX IF NOT EXISTS skill_aliases_skill_id_idx
    ON public.skill_aliases (skill_id);
CREATE INDEX IF NOT EXISTS skill_observations_normalized_idx
    ON public.skill_observations (skill_normalized);
CREATE INDEX IF NOT EXISTS learning_resources_cost_status_idx
    ON public.learning_resources (cost_status);
CREATE INDEX IF NOT EXISTS learning_resource_skills_skill_id_idx
    ON public.learning_resource_skills (skill_id);

